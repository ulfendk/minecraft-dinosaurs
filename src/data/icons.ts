/** Speckled egg icon in a creature's colours. */
export function eggIcon(base: string, spots: string, seed: number): PNG {
  const b = hex(base);
  const s = hex(spots);
  return icon(
    [
      '................',
      '................',
      '.......ee.......',
      '.....eEEEEe.....',
      '....eEhEEEEe....',
      '....eEEEsEEe....',
      '...eEEsEEEEEe...',
      '...eEEEEEsEEe...',
      '...eEsEEEEEEe...',
      '...eEEEEsEEEe...',
      '...eEEEEEEEde...',
      '....eEEsEEdde...',
      '.....eEEEdde....',
      '......eeee......',
      '................',
      '................',
    ],
    { e: toHex(darken(b, 0.35)), E: toHex(b), h: toHex(lighten(b, 0.5)), s: toHex(s), d: toHex(darken(b, 0.12)) },
    seed,
  );
}

/** Colours for a creature egg: pale version of its palette. */
export function eggColours(side: string, pattern: string): [string, string] {
  return [toHex(mix(hex(side), hex('#f4efe2'), 0.55)), toHex(mix(hex(pattern), hex('#3a3026'), 0.3))];
}
